"""Build the Cython/MPFR sandpile extension against a compatible fpylll.

Usage:
    python setup.py build_ext --inplace

If the installed fpylll wheel lacks Cython headers, download the matching
fpylll sdist and set FPYLLL_SOURCE=/path/to/fpylll-0.6.4/src .
"""
import os
import sys
from pathlib import Path
from setuptools import Extension, setup

import fpylll

try:
    from Cython import __version__ as cython_version
    from Cython.Build import cythonize
except ImportError as exc:
    raise RuntimeError("Cython is required: python -m pip install 'Cython>=3.0,<3.2'") from exc

# `src` must be a directory with an `fpylll` subdirectory, NOT the
# `fpylll` directory itself. The Cython include_path is a search root.
source_override = os.environ.get('FPYLLL_SOURCE')
if source_override:
    fpylll_root = Path(source_override).expanduser().resolve()
    if (fpylll_root / 'src' / 'fpylll').is_dir():
        fpylll_root /= 'src'
else:
    fpylll_root = Path(fpylll.__file__).resolve().parent.parent

required = [
    'fpylll/fplll/gso.pxd',
    'fpylll/fplll/decl.pxd',
    'fpylll/fplll/fplll.pxd',
    'fpylll/fplll/integer_matrix.pxd',
    'fpylll/mpfr/mpfr.pxd',
    'fpylll/gmp/random.pxd',
    'fpylll/gmp/types.pxd',
]
missing = [item for item in required if not (fpylll_root / item).is_file()]
if missing:
    req_version = getattr(fpylll, '__version__', '0.6.4')
    raise RuntimeError(
        '\nThe installed fpylll does not expose the Cython declarations needed '
        'by the native-precision bridge.\n'
        f'fpylll version: {req_version}; Cython version: {cython_version}\n'
        f'Looked in: {fpylll_root}\n'
        'Missing files:\n  ' + '\n  '.join(missing) + '\n\n'
        'Download the matching fpylll source WITHOUT reinstalling fpylll:\n'
        f'  python -m pip download --no-deps --no-binary=:all: fpylll=={req_version}\n'
        f'  tar -xzf fpylll-{req_version}.tar.gz\n'
        f'  FPYLLL_SOURCE="$PWD/fpylll-{req_version}/src" '
        'python setup.py build_ext --inplace\n'
        'Use precisely the version installed in your Sage environment.\n'
    )

# Config is generated by fpylll's own setup.py and is often absent from
# source distributions. Reconstruct the *runtime* configuration in a local
# include overlay, without writing into installed fpylll or its sdist.
from fpylll import config as fpylll_config
cfg_dir = Path(__file__).resolve().parent / 'build' / 'cython_include' / 'fpylll'
cfg_dir.mkdir(parents=True, exist_ok=True)
(cfg_dir / 'config.pxi').write_text(
    'DEF HAVE_QD=%s\nDEF HAVE_LONG_DOUBLE=%s\nDEF HAVE_NUMPY=%s\n'
    % (bool(fpylll_config.have_qd),
       bool(fpylll_config.have_long_double),
       False),  # unused by the bridge; do not import NumPy
    encoding='utf-8',
)
include_overlay = str(cfg_dir.parent)

if not fpylll_config.have_qd:
    raise RuntimeError('This patch requires fpylll/fplll compiled with QD support')

print(f'[sandpile] Python: {sys.executable}')
print(f'[sandpile] fpylll: {getattr(fpylll, "__version__", "unknown")}')
print(f'[sandpile] Cython: {cython_version}')
print(f'[sandpile] Cython include root: {fpylll_root}')

ext = Extension(
    'sandpile_mpfr',
    sources=['sandpile_mpfr.pyx'],
    language='c++',
    libraries=['fplll', 'mpfr', 'gmp', 'qd'],
    include_dirs=[str(Path(sys.prefix) / 'include')],
    library_dirs=[str(Path(sys.prefix) / 'lib')],
    extra_compile_args=['-O3', '-std=c++11'],
)

setup(
    name='sandpile-mpfr-bridge',
    version='0.3.0',
    ext_modules=cythonize(
        [ext],
        include_path=[include_overlay, str(fpylll_root)],
        compiler_directives={'language_level': 3},
    ),
)
